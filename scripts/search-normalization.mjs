/** The default reads the committed snapshot, independent of the Node version.
 * To rebuild data, use Unicode 17 Node and official UnicodeData/DerivedAge text.
 * Never replace a deployed function: publish v2 and rebuild stored columns. */
const snapshot = JSON.parse(
  readFileSync(
    new URL("../src/lib/search-unicode-data.json", import.meta.url),
    "utf8",
  ),
);

function nfcCompatibility(unicodeData, ageData) {
  const recent = new Set();
  for (const line of ageData.split("\n")) {
    const [range, age] = line
      .split("#")[0]
      .trim()
      .split(";")
      .map((part) => part.trim());
    if (!age || Number(age) < 16) continue;
    const [start, end = start] = range
      .split("..")
      .map((part) => parseInt(part, 16));
    for (let cp = start; cp <= end; cp++) recent.add(cp);
  }
  const classes = {},
    decompositions = {},
    compositions = {},
    triggers = new Set();
  for (const line of unicodeData.split("\n")) {
    const parts = line.split(";");
    if (parts.length < 6) continue;
    const cp = parseInt(parts[0], 16),
      char = String.fromCodePoint(cp),
      cc = Number(parts[3]);
    if (cc) classes[char] = cc;
    if (recent.has(cp) && cc) triggers.add(char);
    if (recent.has(cp) && parts[5] && !parts[5].startsWith("<")) {
      decompositions[char] = char.normalize("NFD");
      triggers.add(char);
      const pair = parts[5]
        .split(" ")
        .map((point) => String.fromCodePoint(parseInt(point, 16)))
        .join("");
      if ([...pair].length === 2 && pair.normalize("NFC") === char)
        compositions[pair] = char;
      for (const c of pair) if (recent.has(c.codePointAt(0))) triggers.add(c);
    }
  }
  return {
    classes,
    decompositions,
    compositions,
    pattern: "[" + [...triggers].join("") + "]",
    source: "https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt",
    ageSource: "https://www.unicode.org/Public/17.0.0/ucd/DerivedAge.txt",
  };
}

export function searchNormalizationData(unicodeData, ageData) {
  if (process.versions.unicode !== "17.0")
    throw new Error("Use Unicode 17.0 to rebuild v1 data");
  let upper = "",
    lower = "";
  const cased = [],
    ignorable = [];
  const whitespace = [];
  for (let cp = 1; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const char = String.fromCodePoint(cp);
    const mapped = char.toLowerCase();
    if (char !== mapped && char !== "Σ" && char !== "İ") {
      if ([...mapped].length !== 1)
        throw new Error("Unexpected case expansion");
      upper += char;
      lower += mapped;
    }
    if (/\p{Cased}/u.test(char)) cased.push(cp);
    if (/\p{Case_Ignorable}/u.test(char)) ignorable.push(cp);
    if (char.trim() === "") whitespace.push(cp);
  }
  function characterClass(points) {
    const ranges = [];
    const literal = (cp) =>
      String.fromCodePoint(cp).replace(/[\\\]\-^]/g, "\\$&");
    for (let i = 0; i < points.length; i++) {
      const start = points[i];
      while (points[i + 1] === points[i] + 1) i++;
      const end = points[i];
      ranges.push(
        start === end ? literal(start) : literal(start) + "-" + literal(end),
      );
    }
    return "^[" + ranges.join("") + "]$";
  }
  return {
    unicode: process.versions.unicode,
    upper,
    lower,
    cased: characterClass(cased),
    ignorable: characterClass(ignorable),
    whitespace,
    nfcCompatibility: nfcCompatibility(unicodeData, ageData),
  };
}

